"""
Generate frontend/model_results.js from results/*.json.

Run:  .venv/bin/python scripts/export_frontend_results.py

Why: the web app's "Registered Models" list must show REAL measured numbers.
The HTML cannot read results/*.json when opened from disk (file://), so this
script copies the measured metrics into a small JavaScript file the page
loads. Nothing in that file is typed by hand; re-run this script whenever a
results file changes.
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "frontend" / "model_results.js"

# Display order, label and a short description; the numbers come from the files.
MODELS = [
    ("bert_base", "phishguard-bert-base", "BERT-base, fine-tuned by Kasim", ""),
    ("bert_pretrained", "bert-finetuned-phishing (E. Alvarado)", "BERT-large, third-party",
     "Not trained on this test set, but its author used it to pick the best epoch: slightly optimistic."),
    ("tfidf_logreg", "tfidf_logreg", "TF-IDF + Logistic Regression", ""),
    ("features_rf", "features_rf", "Random Forest on hand-crafted features", ""),
    ("tfidf_xgboost", "tfidf_xgboost", "TF-IDF + XGBoost", ""),
    ("heuristic", "heuristic", "Original regex heuristic (in-browser fallback)", ""),
]
SERVED_BY_BACKEND = "bert_base"  # the default model of backend/app.py (src/config.py)


def main() -> None:
    models = []
    for result_id, name, algorithm, note in MODELS:
        r = json.loads((REPO_ROOT / "results" / f"{result_id}.json").read_text())
        models.append({
            "id": result_id, "name": name, "algorithm": algorithm,
            "accuracy": r["accuracy"], "precision": r["precision"], "recall": r["recall"], "f1": r["f1"],
            "fpr": r["fpr"], "roc": r["roc_auc"], "testRows": r["n"],
            "source": f"results/{result_id}.json", "note": note,
            "isActive": result_id == SERVED_BY_BACKEND,
        })
    OUT.write_text(
        "// GENERATED by scripts/export_frontend_results.py from results/*.json. Do not edit by hand.\n"
        "// All metrics are measured on the same held-out test set (see results/split_manifest.json).\n"
        f"const MEASURED_MODELS = {json.dumps(models, indent=2)};\n"
    )
    print(f"wrote {OUT.relative_to(REPO_ROOT)} with {len(models)} models")
    for m in models:
        print(f"  {m['name']:<40} acc {m['accuracy']}  f1 {m['f1']}  from {m['source']}")


if __name__ == "__main__":
    main()
