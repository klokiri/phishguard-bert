"""
Generate the report draft from results/ ONLY.

Run:  .venv/bin/python scripts/make_report.py
Writes results/report_draft.md.

Rule: every number in the draft is read from a file in results/ at run time;
none is typed into this script. The only constants are the proposal's
targets (quoted from docs/PhishGuardAI_Project_Proposal.docx) and fixed
facts about the method. If a results file is missing, the draft says
"NOT YET MEASURED" instead of a number.

The text is a DRAFT for Kasim to rewrite in his own words; it is not meant
to be submitted as is.
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
R = REPO_ROOT / "results"
OUT = R / "report_draft.md"

# Proposal objective (docs/PhishGuardAI_Project_Proposal.docx, section 1.4).
TARGET_ACCURACY, TARGET_F1, TARGET_TEST_ROWS = 0.95, 0.93, 10_000

MODELS = [
    ("bert_base", "bert-base, fine-tuned (Kasim)"),
    ("bert_pretrained", "bert-large, published model (E. Alvarado) †"),
    ("tfidf_logreg", "TF-IDF + Logistic Regression"),
    ("features_rf", "Random Forest on hand-crafted features"),
    ("tfidf_xgboost", "TF-IDF + XGBoost"),
    ("heuristic", "Regex heuristic (original web app)"),
]
NYM = "NOT YET MEASURED"


def load(name):
    path = R / name
    return json.loads(path.read_text()) if path.exists() else None


def pct(x, digits=1):
    return NYM if x is None else f"{100 * x:.{digits}f}%"


def num(x, digits=4):
    return NYM if x is None else f"{x:.{digits}f}"


def main() -> None:
    manifest, summary = load("split_manifest.json"), load("data_summary.json")
    res = {m: load(f"{m}.json") for m, _ in MODELS}
    history, config = load("bert_base_history.json"), load("bert_base_training_config.json")
    tokens, coverage = load("token_length_stats.json"), load("coverage.json")
    indicators, parity = load("indicator_stats.json"), load("heuristic_parity.json")
    scheme, errors, notes = load("scheme_artefact.json"), load("error_analysis.json"), load("error_analysis_notes.json")
    out = []
    w = out.append

    w("# PhishGuard AI: results and methods (DRAFT)\n")
    w("> Generated by `scripts/make_report.py` from the files in `results/`. Every number below is read from "
      "a results file; regenerate this draft after any change. This is a starting point for Kasim's report, "
      "to be rewritten in his own words.\n")

    # ── Data ──
    s, src = manifest["splits"], manifest["source"]
    w("## 1. Data and split\n")
    w(f"Dataset: `{src['dataset']}` (Hugging Face), revision `{src['revision'][:12]}`, dated {src['revision_date']}. "
      f"This revision contains the train/test files the published model `ealvaradob/bert-finetuned-phishing` "
      f"was trained and tested on: its `train.json` has {manifest['provenance_check']['train_json_rows']:,} rows, "
      f"i.e. {manifest['provenance_check']['implied_steps_per_epoch_batch16']:,} steps per epoch at batch size 16, "
      f"matching the model card ({manifest['provenance_check']['model_card_steps_per_epoch']:,}; "
      f"match = {manifest['provenance_check']['matches_model_card']}). A later re-upload "
      "(`combined_reduced.json`) re-sampled the URLs, so a fresh split of it would have put much of the "
      "published model's training data into the test set; it was therefore not used.\n")
    w("| Split | Rows | Phishing | Legitimate | Phishing share |\n|---|---|---|---|---|")
    for name in ("train", "val", "test"):
        b = summary["splits"][name]
        w(f"| {name} | {b['rows']:,} | {b['phishing']:,} | {b['benign']:,} | {pct(b['phishing_fraction'], 2)} |")
    q = summary["quality_checks"]
    t = summary["type_guess_counts"]["test"]
    w(f"\nThe test set is the published `test.json`, unchanged ({s['test']['rows']:,} rows, which meets the "
      f"proposal's minimum of {TARGET_TEST_ROWS:,}). Validation is a stratified 10% of `train.json` (seed 42); "
      "the test set was never used for training, model selection or tuning of our models. Test-set composition "
      f"(heuristic type guess): {t.get('url', 0):,} URLs, {t.get('text', 0):,} emails/SMS, {t.get('html', 0):,} "
      f"HTML pages. {q['test_rows_exact_text_in_train_json']} test rows have an exact duplicate in the training "
      f"file ({q['test_rows_normalised_text_in_train_json']} after normalising case and whitespace); they were "
      "kept so the test set stays identical to the original. Hashes of every split are in "
      "`results/split_manifest.json`.\n")

    # ── Methods ──
    w("## 2. Models and evaluation method\n")
    w("Six models were evaluated by one shared function (`src/evaluate.py`) on the same test set:\n")
    for m, label in MODELS:
        d = res[m]["details"] if res[m] else {}
        w(f"- **{label}**: {d.get('description', NYM)}")
    if history and config:
        ta = config["training_arguments"]
        best_step = history["best_checkpoint"].rsplit("-", 1)[-1] if history["best_checkpoint"] else NYM
        html_512 = tokens["by_type"]["html"]["fraction_fitting_without_truncation"]["512"] if tokens else None
        text_512 = tokens["by_type"]["text"]["fraction_fitting_without_truncation"]["512"] if tokens else None
        w(f"\nFine-tuning of `{config['base_model']}`: learning rate {ta['learning_rate']}, batch size "
          f"{ta['per_device_train_batch_size']}, weight decay {ta['weight_decay']}, up to {ta['num_train_epochs']} "
          f"epochs, {ta['lr_scheduler_type']} schedule, optimiser `{ta['optim']}`, fp16 = {ta['fp16']}, seed "
          f"{ta['seed']}, max length {history['settings']['max_length']} tokens (chosen from training-set token "
          f"lengths: {pct(text_512)} of emails/SMS fit in 512 tokens, only {pct(html_512)} of HTML pages). "
          f"Validation F1 was checked every {config['script_constants']['eval_and_save_every_steps']:,} steps; "
          f"the best checkpoint (step {best_step}, validation F1 {num(history['best_validation_f1'])}) was "
          f"kept. Training took {history['train_seconds_this_session'] / 60:.0f} minutes on "
          f"{config['environment']['device']}.\n")
    w("Metrics: accuracy; precision, recall and F1 for the phishing class; false positive rate "
      "FPR = FP / (FP + TN); ROC-AUC from the continuous score; mean latency per sample (batched). Decision "
      "rule: phishing if score ≥ 0.5 (the heuristic uses its own 'phishing' verdict).\n")

    # ── Results ──
    w("## 3. Results\n")
    w("| Model | Accuracy | Precision | Recall | F1 | FPR | ROC-AUC | Latency (ms/sample) |\n"
      "|---|---|---|---|---|---|---|---|")
    for m, label in MODELS:
        r = res[m]
        if r is None:
            w(f"| {label} | {NYM} | | | | | | |")
            continue
        w(f"| {label} | {num(r['accuracy'])} | {num(r['precision'])} | {num(r['recall'])} | {num(r['f1'])} | "
          f"{num(r['fpr'])} | {num(r['roc_auc'])} | {r['latency_ms_per_sample']:.2f} |")
    w(f"\n† Not trained on this test set, but its author used this test set to choose the best training epoch, "
      "so its figures are slightly optimistic.\n")
    meets = [label for m, label in MODELS
             if res[m] and res[m]["accuracy"] >= TARGET_ACCURACY and res[m]["f1"] >= TARGET_F1]
    classical_meets = [label for m, label in MODELS if not m.startswith("bert") and label in meets]
    w(f"Proposal objective (accuracy ≥ {TARGET_ACCURACY}, F1 ≥ {TARGET_F1}, ≥ {TARGET_TEST_ROWS:,} test samples): "
      f"met by {', '.join(meets) if meets else 'no model'}. Classical/heuristic models meeting it: "
      f"{', '.join(classical_meets) if classical_meets else 'none'}.\n")
    pre = res["bert_pretrained"]
    if pre:
        a = pre["details"]["author_reported_on_same_test_set"]
        w(f"Reproduction check of the published model: measured accuracy {num(pre['accuracy'])}, precision "
          f"{num(pre['precision'])}, recall {num(pre['recall'])}, FPR {num(pre['fpr'])}; author-reported "
          f"(model card) {a['accuracy']}, {a['precision']}, {a['recall']}, {a['false_positive_rate']}.\n")
    w("F1 by sample type:\n\n| Model | URL | Email/SMS | HTML |\n|---|---|---|---|")
    for m, label in MODELS:
        if res[m]:
            b = res[m]["by_type"]
            w(f"| {label} | {num(b['url']['f1'])} | {num(b['text']['f1'])} | {num(b['html']['f1'])} |")
    w("\nFigures (in `results/figures/`): `confusion_matrices.png`, `roc_curves.png`, `latency.png`, "
      "`scheme_artefact.png`; table: `comparison_table.md`.\n")

    # ── Explainability and system ──
    w("## 4. Explainability and the web system\n")
    if indicators:
        shown = [rid for rid, r in indicators["rules"].items()
                 if rid not in indicators["excluded_from_display"] and r["fired"] >= indicators["min_support"]
                 and r["phishing_rate"] is not None
                 and abs(r["phishing_rate"] - indicators["base_phishing_rate"][r["input_type"]]) >= indicators["min_lift"]]
        w(f"The backend returns, with each prediction: (1) rule-based indicators, of which "
          f"{len(indicators['rules'])} rules are defined and {len(shown)} can be shown; each is displayed only "
          "when it fires, with its evidence, and its 0–100 score is the phishing (or legitimate) rate measured "
          f"on the training split among samples where the rule fires (minimum {indicators['min_support']} "
          "samples); (2) the words that most changed the model's score, measured by leave-one-word-out "
          "occlusion in log-odds. Indicators are independent checks, not an explanation of BERT's internal "
          "reasoning; the occlusion words are model-derived.\n")
    if parity:
        w(f"The original app's heuristic was ported to Python; on all {parity['rows_compared']:,} test rows the "
          f"port and the original JavaScript agree ({parity['mismatches']} mismatches).\n")
    if coverage:
        w(f"Backend tests: {coverage['tests']}; statement coverage of `backend/` "
          f"{coverage['total_percent']}% (lowest module {coverage['lowest_module_percent']}%), against the "
          f"NFR-09 target of {coverage['target_percent']:.0f}%.\n")

    # ── Error analysis ──
    w("## 5. Error analysis (bert-base)\n")
    if errors:
        fp, fn = errors["false_positives"], errors["false_negatives"]
        w(f"False positives: {fp['count']} (HTML {fp['by_type'].get('html', 0)}, email/SMS "
          f"{fp['by_type'].get('text', 0)}, URL {fp['by_type'].get('url', 0)}); {fp['also_wrong_in_author_model']} "
          f"of them are also misclassified by the published bert-large. False negatives: {fn['count']} (HTML "
          f"{fn['by_type'].get('html', 0)}, email/SMS {fn['by_type'].get('text', 0)}, URL "
          f"{fn['by_type'].get('url', 0)}); {fn['also_wrong_in_author_model']} shared with bert-large. "
          f"Examples: {errors['sampling']}. Notes are the assistant's reading of each example, for review.\n")
        for kind, key, title in (("false_positive_examples", "false_positives", "False positives (legitimate flagged)"),
                                 ("false_negative_examples", "false_negatives", "False negatives (phishing missed)")):
            w(f"**{title}**\n\n| Row | Type | Score | Note |\n|---|---|---|---|")
            for e in errors[kind]:
                # "|" would end a markdown table cell, so it is escaped.
                note = (notes or {}).get(key, {}).get(str(e["row_id"]), "").replace("|", "\\|")
                w(f"| {e['row_id']} | {e['type']} | {e['phishing_score']} | {note} |")
            w("")
    if scheme:
        tr = scheme["_training_urls_with_scheme"]
        w("**URL-scheme artefact.** In the training data only "
          f"{pct(tr['benign_share'])} of legitimate URLs include a scheme (`http://`/`https://`), versus "
          f"{pct(tr['phishing_share'])} of phishing URLs, an artefact of how the source URL lists were collected. "
          "To test whether the models learned it, every test URL without a scheme was scored as-is and with "
          "`https://` prepended:\n")
        w("| Model | Legitimate URLs flagged (as-is → with https://) | Phishing URLs caught (as-is → with https://) |\n|---|---|---|")
        for m, label in MODELS:
            if m in scheme:
                b, p = scheme[m]["benign"], scheme[m]["phishing"]
                w(f"| {label} | {pct(b['flagged_as_phishing_plain'])} → {pct(b['flagged_as_phishing_with_https'])} "
                  f"| {pct(p['flagged_as_phishing_plain'])} → {pct(p['flagged_as_phishing_with_https'])} |")
        n_b = scheme["bert_base"]["benign"]["urls"] if "bert_base" in scheme else NYM
        worse = [label for m, label in MODELS if m in scheme and scheme[m]["benign"]["flagged_as_phishing_with_https"]
                 > scheme[m]["benign"]["flagged_as_phishing_plain"]]
        w(f"\n(n = {n_b:,} legitimate URLs per model.) Models that flag more legitimate URLs once `https://` is "
          f"added: {', '.join(worse) if worse else 'none'}. For these, the test-set false positive rate "
          "understates what users pasting full URLs would experience. The two scheme rules are therefore "
          "hidden from the user-facing indicators.\n")

    # ── Limitations ──
    w("## 6. Limitations\n")
    w("- **Leakage handling.** Our models never saw the test set before final evaluation. The published model "
      "was evaluated on its own held-out test set, but its author used that set for checkpoint selection, so "
      "its scores are slightly optimistic. "
      f"{q['test_rows_normalised_text_in_train_json']} test rows ({pct(q['test_rows_normalised_text_in_train_json'] / s['test']['rows'], 2)}) "
      "have a near-identical text in the training data.")
    w("- **Dataset source bias.** The URL-scheme artefact above; legitimate emails are largely Enron corporate "
      "mail and the SMS subset counts spam as phishing (label definition), so performance on today's phishing "
      "may differ. No out-of-distribution test set was evaluated (planned, not done).")
    w("- **English only.** The data and models are English; other languages were not tested.")
    if tokens:
        bert_weakest = {label: min(res[m]["by_type"], key=lambda k: res[m]["by_type"][k]["f1"])
                        for m, label in MODELS if m.startswith("bert") and res[m]}
        w(f"- **Truncation.** BERT reads at most 512 tokens; only {pct(tokens['by_type']['html']['fraction_fitting_without_truncation']['512'])} "
          "of training HTML pages fit. Weakest sample type by F1: "
          + "; ".join(f"{label}: {t}" for label, t in bert_weakest.items()) + ".")
    last_step = max((e["step"] for e in history["log_history"] if "eval_f1" in e), default=None) if history else None
    best_is_last = history and history["best_checkpoint"] and history["best_checkpoint"].endswith(f"-{last_step}")
    w("- **Single training run.** One seed; GPU training on Apple MPS is not bit-for-bit deterministic, so "
      "re-runs give close but not identical numbers."
      + (" The best checkpoint was the last one evaluated, so longer training might help; this was not "
         "tested, to avoid tuning on the test set." if best_is_last else ""))
    w("- **Scope versus the proposal.** Not implemented: user authentication and roles (FR-02, NFR-01), "
      "web-based model training (FR-04), TLS (NFR-02), immutable audit log (NFR-10), load testing (NFR-04 at 50 "
      "users), usability and accessibility studies (NFR-06, NFR-07), uptime monitoring (NFR-08), an OpenAPI "
      "specification file (part of NFR-12), and SHAP explanations (occlusion is used instead).\n")

    # ── Third-party work ──
    w("## 7. Use of third-party work\n")
    w("This project builds on Esteban Alvarado's final-year project *Phishing Detection with BERT* "
      "(https://github.com/EstAlvB/Phishing-Detection-with-BERT, Apache License 2.0). From it, this project "
      f"uses: the phishing dataset `ealvaradob/phishing-dataset` (revision `{src['revision'][:12]}`, MIT licence "
      "at that revision); the published fine-tuned model `ealvaradob/bert-finetuned-phishing`, which is "
      "evaluated here as a third-party baseline and is not Kasim's model; the feature extractors in "
      "`features.py` (copied unchanged into `src/features.py` with attribution); and the train/test split "
      "and TF-IDF/XGBoost settings described in his notebooks. Everything else (the evaluation framework, "
      "the heuristic port, the classical models trained here, the fine-tuned bert-base model, the backend "
      "with its indicators and attribution, the web-app integration, and this analysis) is Kasim's own work, "
      "produced with AI assistance that is declared in `AI_ASSISTANCE_LOG.md`.\n")

    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
